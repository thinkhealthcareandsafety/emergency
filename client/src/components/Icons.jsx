/** Picks a glyph from the role's key/label so custom roles added in admin still get a sensible icon. */
export function roleIcon(key = '', label = '') {
  const s = `${key} ${label}`.toLowerCase();
  if (/fire/.test(s)) return 'flame';
  if (/aid|medic|nurse|doctor|health/.test(s)) return 'medical';
  if (/secur|guard/.test(s)) return 'shield';
  if (/engin|util|maint|tech|electr/.test(s)) return 'wrench';
  if (/evac|marshal|exit/.test(s)) return 'exit';
  if (/incident|control|lead|command|chief|manager/.test(s)) return 'megaphone';
  return 'person';
}

export function emergencyIcon(type = '') {
  const s = type.toLowerCase();
  if (/fire|smoke|gas/.test(s)) return 'flame';
  if (/medic/.test(s)) return 'medical';
  if (/secur|bomb|threat/.test(s)) return 'shield';
  return 'alert';
}
